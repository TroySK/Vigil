CREATE TABLE IF NOT EXISTS kv (
  k TEXT PRIMARY KEY,
  v TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS samples (
  id TEXT NOT NULL,
  at INTEGER NOT NULL,
  ms INTEGER NOT NULL,
  up INTEGER NOT NULL,
  place TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_samples ON samples (id, at);
CREATE TABLE IF NOT EXISTS gaps (
  id TEXT NOT NULL,
  at INTEGER NOT NULL,
  upto INTEGER,
  why TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_gaps ON gaps (id, at);
